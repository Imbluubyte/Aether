void Font::buildAtlas(std::vector<uint8_t>& rgba, int& w, int& h) {
    w = kCols * kCellW;
    h = kRows * kCellH;
    rgba.assign((size_t)w * (size_t)h * 4, 0);
    for (int g = 0; g < 95; g++) {
        int cx = (g % kCols) * kCellW, cy = (g / kCols) * kCellH;
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (kGlyphs[g][col] & (1 << row)) {
                    uint8_t* p = &rgba[((size_t)(cy + row) * (size_t)w + (size_t)(cx + col)) * 4];
                    p[0] = p[1] = p[2] = p[3] = 255;
                }
    }
}

Vec2 Font::measure(const std::string& text, float size) const {
    float maxW = 0, cur = 0;
    int lines = 1;
    for (char ch : text) {
        if (ch == '\n') { maxW = std::max(maxW, cur); cur = 0; lines++; continue; }
        cur += kCellW * size;
    }
    maxW = std::max(maxW, cur);
    return {maxW > 0 ? maxW - size : 0, lines * kCellH * size - size};
}

void Font::draw(SpriteBatch& batch, const std::string& text, float x, float y, float size, Color c, int align) const {
    const float aw = (float)(kCols * kCellW), ah = (float)(kRows * kCellH);
    size_t i = 0;
    float cy = y;
    while (i <= text.size()) {
        size_t e = text.find('\n', i);
        if (e == std::string::npos) e = text.size();
        std::string line = text.substr(i, e - i);
        float lw = line.empty() ? 0 : (float)line.size() * kCellW * size - size;
        float cx = align == 1 ? x - lw * 0.5f : (align == 2 ? x - lw : x);
        for (char ch : line) {
            int g = (unsigned char)ch;
            g = (g >= 32 && g <= 126) ? g - 32 : '?' - 32;
            if (g != 0) {
                float u = (float)((g % kCols) * kCellW), v = (float)((g / kCols) * kCellH);
                batch.axisAlignedRect(tex_, cx, cy, 5 * size, 7 * size, Rect{u / aw, v / ah, 5.f / aw, 7.f / ah}, c);
            }
            cx += kCellW * size;
        }
        cy += kCellH * size;
        i = e + 1;
    }
}

